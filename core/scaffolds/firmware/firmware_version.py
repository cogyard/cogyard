# scripts/firmware_version.py — the SINGLE build-time source of version + commit
# for this firmware. Seeded by cogyard's `firmware` kind; it is yours to edit.
#
# A PlatformIO pre-build script. Hook it up once, in platformio.ini:
#
#   [env]
#   extra_scripts = pre:scripts/firmware_version.py
#
# (add it to any extra_scripts list you already have). Every `pio run` then
# writes version.h before it compiles anything, and the sketch includes it:
#
#   #include "version.h"
#   // FW_VERSION "1.2.0"   FW_COMMIT "abc1234"   FW_ENV "app"
#   // FW_STAMP   "v1.2.0 (abc1234)"
#
# Show FW_STAMP on the device's own screen: the running firmware must say which
# version and commit it is.
#
# version.h is generated, so it is never hand-edited and never committed. It is
# written into the build folder (.pio/build/<env>/stamp/), beside a .gitignore
# that ignores it whatever the project's own .gitignore says, and that folder is
# put first on the include path. It is rewritten only when its text changes, so
# an unchanged commit does not recompile what includes it.
#
# The version is the root package.json's "version" (the project's release
# counter); the commit is `git rev-parse --short HEAD`. With no package.json the
# version is 0.0.0, and outside git the commit is no-git.

import json
import os
import subprocess

Import("env")  # noqa: F821 -- provided by PlatformIO (SCons) when it runs this script

ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
OUT = os.path.join(env.subst("$BUILD_DIR"), "stamp")  # noqa: F821
ENV_NAME = env.subst("$PIOENV")  # noqa: F821


def read_version():
    try:
        with open(os.path.join(ROOT, "package.json"), encoding="utf-8") as f:
            return str(json.load(f).get("version") or "0.0.0")
    except (OSError, ValueError):
        return "0.0.0"


def read_commit():
    try:
        done = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        )
        return done.stdout.strip() or "no-git"
    except (OSError, subprocess.CalledProcessError):
        return "no-git"


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_if_changed(path, text):
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


version = read_version()
commit = read_commit()
stamp = "v%s (%s)" % (version, commit)

header = "\n".join([
    "// version.h — GENERATED by scripts/firmware_version.py before every build.",
    "// Never hand-edit, never commit: the next build rewrites it.",
    "#pragma once",
    "#define FW_VERSION " + c_string(version),
    "#define FW_COMMIT " + c_string(commit),
    "#define FW_ENV " + c_string(ENV_NAME),
    "#define FW_STAMP " + c_string(stamp),
    "",
])

os.makedirs(OUT, exist_ok=True)
write_if_changed(os.path.join(OUT, ".gitignore"), "# Generated by scripts/firmware_version.py\n*\n")
changed = write_if_changed(os.path.join(OUT, "version.h"), header)
env.Prepend(CPPPATH=[OUT])  # noqa: F821

print("firmware_version: %s [%s] -> %s%s" % (
    stamp, ENV_NAME, os.path.join(OUT, "version.h"), "" if changed else " (unchanged)",
))
