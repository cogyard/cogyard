// test/brief-silence.test.mjs — THE SILENCE RULE: does the nightly brief job
// correctly decide that nothing happened?
//
// This is the economics of the whole feature and it was wrong in production.
// Up to 2026-08-25 the answer was "yes, something happened" on essentially every
// project every night — this repo had six briefs and none carried forward, at
// ~$0.15 a night, for days whose honest summary was "nothing happened". Two
// causes, both reproduced below so they cannot come back:
//
//   1. `capturedAt` in the activity ledger is a HARVEST time, not an activity
//      time, and the ledger is append-only — a finished session gets re-appended
//      with a fresh capturedAt on every collection. Using it as a fallback clock
//      made a session that ended on Monday read as new activity every night
//      after — observed on a real store, where one finished session was
//      re-harvested minutes before the 05:00 run and duly reported as activity.
//   2. Task-file mtime is not task-file change. `env claim` + `env release`
//      rewrites a file to its original bytes; `tasks sync push` regenerates
//      INDEX.md from any project sharing the store. Both bought an agent call.
//
// The counterpart test is briefs.test.mjs (the FILE FORMAT the writer and reader
// share). This one is about the decision made before anything is written.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, utimesSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const HOME = mkdtempSync(join(tmpdir(), 'cogyard-silence-home-'));
process.env.COGYARD_HOME = HOME;
mkdirSync(join(HOME, 'usage'), { recursive: true });

const { taskFiles, tasksDigest, taskEditsSince, sessionsSince } =
  await import('../extras/addons/project-brief/inputs.mjs');

const LEDGER = join(HOME, 'usage', 'activity.jsonl');

function ledger(rows) {
  writeFileSync(LEDGER, rows.map((r) => JSON.stringify(r)).join('\n') + '\n');
}

function store(files) {
  const dir = mkdtempSync(join(tmpdir(), 'cogyard-silence-'));
  const tasks = join(dir, '.cogyard', 'tasks');
  mkdirSync(tasks, { recursive: true });
  for (const [name, body] of Object.entries(files)) writeFileSync(join(tasks, name), body);
  return tasks;
}

// --- what counts as a task file ----------------------------------------------

test('only task files are task files — INDEX.md and friends are not', () => {
  const tasks = store({
    '001-first.md': 'a',
    '042-another-one.md': 'b',
    'INDEX.md': 'generated by every sync push',
    'IDEAS.md': 'not a task',
    'HANDOFF-something.md': 'not a task',
    'axes.json': '{}',
    'notes.txt': 'x',
  });
  assert.deepEqual(taskFiles(tasks), ['001-first.md', '042-another-one.md']);
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

test('a follow-on task id (039a) is a task file', () => {
  // The bug this guards: a plain `\d+-` matcher misses the letter-suffix form,
  // so edits to a follow-on task would not count as news and a night spent
  // working on it would read as a quiet night.
  const tasks = store({ '039a-follow-on.md': 'a', '013.5-sub-task.md': 'b' });
  assert.deepEqual(taskFiles(tasks), ['013.5-sub-task.md', '039a-follow-on.md']);
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

test("the add-on's idea of a task filename agrees with core's", async () => {
  // The add-on installs OUTSIDE the repo and cannot import core synchronously,
  // so its TASK_FILE is a second spelling of core/validate.mjs's id grammar.
  // Two spellings drift; this is what catches it. If the grammar moves, this
  // fails here rather than silently in a nightly run nobody is watching.
  const { normalizeTaskId } = await import('../core/index.mjs');

  // core's own rule for "is this filename a task file": it yields an id token.
  const coreSaysTask = (f) => {
    const m = f.match(/^(\d+(?:\.\d+)?[a-z]?)/);
    return !!(f.endsWith('.md') && f !== 'INDEX.md' && m && normalizeTaskId(m[1]) && /^\d+(?:\.\d+)?[a-z]?-/.test(f));
  };

  const corpus = [
    '001-first.md', '42-no-padding.md', '039a-follow-on.md', '013.5-sub-task.md',
    '134-daily-quiet-days.md', '007s-letter.md',
    'INDEX.md', 'IDEAS.md', 'HANDOFF-bucketof.md', 'drift.md', 'axes.json',
    'notes.txt', 'README.md', '2026-01-01.md', 'no-digit-prefix.md',
  ];

  const tasks = store(Object.fromEntries(corpus.filter((f) => f.endsWith('.md')).map((f) => [f, 'x'])));
  const mine = new Set(taskFiles(tasks));
  for (const f of corpus) {
    if (!f.endsWith('.md')) continue;
    assert.equal(mine.has(f), coreSaysTask(f), `disagreement on ${f}`);
  }
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

// --- the digest: content, not timestamps -------------------------------------

test('rewriting a task file with identical bytes does not move the digest', () => {
  const tasks = store({ '001-first.md': 'body\n' });
  const before = tasksDigest(tasks);
  // What `env claim` followed by `env release` does: same content, new mtime.
  writeFileSync(join(tasks, '001-first.md'), 'body\n');
  assert.equal(tasksDigest(tasks), before, 'a byte-identical rewrite is not a change');
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

test('regenerating INDEX.md does not move the digest', () => {
  const tasks = store({ '001-first.md': 'body\n', 'INDEX.md': 'old index\n' });
  const before = tasksDigest(tasks);
  writeFileSync(join(tasks, 'INDEX.md'), 'a completely different generated index\n');
  assert.equal(tasksDigest(tasks), before, 'INDEX.md is generated, never news');
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

test('a real edit to a task file moves the digest', () => {
  const tasks = store({ '001-first.md': 'body\n' });
  const before = tasksDigest(tasks);
  writeFileSync(join(tasks, '001-first.md'), 'body, now with an actual change\n');
  assert.notEqual(tasksDigest(tasks), before);
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

test('adding and removing a task file both move the digest', () => {
  const tasks = store({ '001-first.md': 'a\n' });
  const before = tasksDigest(tasks);
  writeFileSync(join(tasks, '002-second.md'), 'b\n');
  const withTwo = tasksDigest(tasks);
  assert.notEqual(withTwo, before, 'a new task is news');
  rmSync(join(tasks, '002-second.md'));
  assert.equal(tasksDigest(tasks), before, 'and removing it returns the store to where it was');
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

test('a store with no task dir digests as null rather than throwing', () => {
  assert.equal(tasksDigest(join(tmpdir(), 'cogyard-silence-nope', '_tasks')), null);
  assert.equal(tasksDigest(null), null);
});

// --- which files moved (only ever asked once the digest already said yes) -----

test('taskEditsSince names task files by mtime and skips generated ones', () => {
  const tasks = store({ '001-first.md': 'a\n', '002-second.md': 'b\n', 'INDEX.md': 'i\n' });
  const old = new Date('2026-01-01T00:00:00Z');
  for (const f of ['001-first.md', '002-second.md', 'INDEX.md']) utimesSync(join(tasks, f), old, old);
  writeFileSync(join(tasks, '002-second.md'), 'b changed\n');

  const edits = taskEditsSince(tasks, '2026-01-02T00:00:00Z');
  assert.deepEqual(edits.map((e) => e.file), ['002-second.md']);
  rmSync(join(tasks, '..'), { recursive: true, force: true });
});

// --- sessions: the owner typing, timed by his own prompt ----------------------

const CUT = '2026-08-24T12:00:00.000Z';

test('a promptless session is not activity, however recently it was harvested', async () => {
  // The exact shape that broke it: one session, four harvest rows, the later
  // ones with no prompts and a capturedAt long after the cut.
  ledger([
    { project: 'demo', sessionId: 'sess-a', prompts: ['2026-08-24T09:00:00.000Z'], capturedAt: '2026-08-24T09:05:00.000Z' },
    { project: 'demo', sessionId: 'sess-a', prompts: [], capturedAt: '2026-08-25T05:39:49.460Z' },
    { project: 'demo', sessionId: 'sess-a', prompts: [], capturedAt: '2026-08-26T05:39:49.460Z' },
  ]);
  assert.deepEqual(await sessionsSince('demo', CUT), [],
    'the session ended before the cut; re-harvesting it does not make it new');
});

test('a session counts from the owner\'s last prompt, not the harvest', async () => {
  ledger([
    { project: 'demo', sessionId: 'sess-b', prompts: ['2026-08-24T18:00:00.000Z'], capturedAt: '2026-08-24T18:30:00.000Z' },
  ]);
  const rows = await sessionsSince('demo', CUT);
  assert.equal(rows.length, 1);
  assert.equal(rows[0].at, '2026-08-24T18:00:00.000Z');
});

test('one session harvested many times is counted once, at its newest prompt', async () => {
  ledger([
    { project: 'demo', sessionId: 'sess-c', prompts: ['2026-08-24T18:00:00.000Z'], capturedAt: '2026-08-24T18:05:00.000Z' },
    { project: 'demo', sessionId: 'sess-c', prompts: ['2026-08-24T18:00:00.000Z', '2026-08-24T19:30:00.000Z'], capturedAt: '2026-08-24T19:35:00.000Z' },
    { project: 'demo', sessionId: 'sess-c', prompts: [], capturedAt: '2026-08-25T05:00:00.000Z' },
  ]);
  const rows = await sessionsSince('demo', CUT);
  assert.equal(rows.length, 1, 'three harvest rows are still one session');
  assert.equal(rows[0].at, '2026-08-24T19:30:00.000Z');
  assert.equal(rows[0].prompts, 2);
});

test('sessions in another project are not this project\'s activity', async () => {
  ledger([
    { project: 'other', sessionId: 'sess-d', prompts: ['2026-08-25T09:00:00.000Z'], capturedAt: '2026-08-25T09:05:00.000Z' },
  ]);
  assert.deepEqual(await sessionsSince('demo', CUT), []);
});

test('sessions come back newest first', async () => {
  ledger([
    { project: 'demo', sessionId: 'old', prompts: ['2026-08-24T13:00:00.000Z'], capturedAt: '2026-08-24T13:05:00.000Z' },
    { project: 'demo', sessionId: 'new', prompts: ['2026-08-25T13:00:00.000Z'], capturedAt: '2026-08-25T13:05:00.000Z' },
  ]);
  assert.deepEqual((await sessionsSince('demo', CUT)).map((r) => r.sessionId), ['new', 'old']);
});

test('an empty ledger is a quiet project, not an error', async () => {
  writeFileSync(LEDGER, '');
  assert.deepEqual(await sessionsSince('demo', CUT), []);
});
